    fun systemLanguage(): String {
        return when (Locale.getDefault().language?.lowercase()) {
            "uk", "ua" -> UK
            "ru" -> RU
            else -> EN
        }
    }

    fun resolve(pref: String): String = if (pref == AUTO) systemLanguage() else pref

